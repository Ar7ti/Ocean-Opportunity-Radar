// You can pass additional config via defineConfig({ vite: { ... }, etc... }) if needed.
import { loadEnv } from "vite";

// Load only server settings; never inject these into the client bundle.
const privateEnv = loadEnv(process.env["NODE_ENV"] || "development", process.cwd(), "");
for (const key of ["OPENAI_API_KEY", "OPENAI_MODEL", "AI_REQUEST_LIMIT"]) {
  if (!process.env[key] && privateEnv[key]) process.env[key] = privateEnv[key];
}

import { defineConfig } from "@lovable.dev/vite-tanstack-config";

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
});
